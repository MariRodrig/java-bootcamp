

package ex08classeseobjetos;

//  Crie uma classe chamada Pet.
//  Dê a ela três atributos: nome (String), raca (String) e peso (double).

public class Pet {
    public String nome;
    public String raca;
    public double peso;

    public Pet(String nome, String raca, double peso) {
        this.nome = nome;
        this.raca = raca;
        this.peso = peso;
    }
}
